#!/usr/bin/env node
'use strict';
// Generates the built-in themes in public/themes/<id>/ from the specs in tools/themes/specs/.
// Usage: node tools/themes/build.js [--specs <dir>] [--out <dir>] [id ...]   (no ids = all)
// --specs/--out build your own private themes, e.g. --specs ~/.agent-floor/theme-specs --out ~/.agent-floor/themes

const fs = require('fs');
const path = require('path');
const { character } = require('./character');

const ROOT = path.join(__dirname, '..', '..');
const args = process.argv.slice(2);
const flag = (name, dflt) => { const i = args.indexOf(name); if (i < 0) return dflt; const v = args[i + 1]; args.splice(i, 2); return path.resolve(v); };
const SPECS = flag('--specs', path.join(__dirname, 'specs'));
const OUT = flag('--out', path.join(ROOT, 'public', 'themes'));

const ROLE_TEXT = {
  thinking: 'Thinking', planning: 'Planning', reading: 'Reading', writing: 'Writing code', running: 'Running', tests: 'Testing',
  build: 'Building', deploy: 'Deploying', data: 'Querying data', review: 'Reviewing', git: 'Git work', delegating: 'Handing off',
  browsing: 'Using tools', waiting: 'Needs you', asking: 'Has a question', idle: 'Resting', done: 'Done',
};
const want = args;
for (const file of fs.readdirSync(SPECS).filter((f) => f.endsWith('.js')).sort()) {
  const spec = require(path.join(SPECS, file));
  if (want.length && !want.includes(spec.id)) continue;
  const dir = path.join(OUT, spec.id);
  fs.rmSync(dir, { recursive: true, force: true });
  fs.mkdirSync(dir, { recursive: true });
  const roles = {};
  const labels = {};
  for (const [role, c] of Object.entries(spec.cast)) {
    const name = `${role}.svg`;
    fs.writeFileSync(path.join(dir, name), character({ ...c, title: `${c.name}: ${role}` }));
    roles[role] = name;
    if (c.name && role !== 'helper') labels[role] = c.label || `${c.name} · ${ROLE_TEXT[role] || role}`;
  }
  for (const [name, svg] of Object.entries(spec.files || {})) fs.writeFileSync(path.join(dir, name), svg.trim() + '\n');
  // The 3D floor builds characters from the same cast data, so ship it as plain JSON next to the SVGs.
  fs.writeFileSync(path.join(dir, 'model.json'), JSON.stringify({ version: 1, cast: spec.cast, room3d: spec.room3d || {} }) + '\n');
  const manifest = {
    id: spec.id, name: spec.name, version: spec.version || '1.0.0', author: 'agent-floor', description: spec.description, kind: 'vector',
    tint: !!spec.tint, room: spec.room, roles: { default: roles[spec.defaultRole || 'thinking'], ...roles }, celebration: spec.celebration || {},
    labels, names: Object.fromEntries(Object.entries(spec.cast).map(([r, c]) => [r, c.name])), feed: spec.feed || {},
    header: spec.header, model: 'model.json', size: { sit: 30, helper: 13, aspect: 1.6, ...(spec.size || {}) },
  };
  fs.writeFileSync(path.join(dir, 'theme.json'), JSON.stringify(manifest, null, 2) + '\n');
  // A cast list, so people can see who does what.
  const rows = Object.entries(spec.cast).map(([role, c]) => `| ${role === 'helper' ? 'Helper (subagent)' : ROLE_TEXT[role] || role} | ${c.name} | ${(labels[role] || '').split(' · ')[1] || ''} |`);
  fs.writeFileSync(path.join(dir, 'README.md'), `# ${spec.name}\n\n${spec.description}\n\n| When the agent is… | Character | Tag text |\n| --- | --- | --- |\n${rows.join('\n')}\n\nGenerated by \`npm run build:themes\` from \`${path.join(path.relative(ROOT, SPECS) || '.', file)}\`. Edit the spec, not these files.\n`);
  console.log(`built ${spec.id}: ${Object.keys(roles).length} characters`);
}
